// Go API reference (gomarkdoc)

/**
 * The Go toolchain the module selects (go.mod's go line, or the local go if it is newer), as a
 * GOTOOLCHAIN value such as "go1.27.3".
 *
 * `go run pkg@version` builds outside this module, so it ignores go.mod and builds gomarkdoc with
 * whatever go comes first in PATH. An older go (a system /usr/local/go, say) gives gomarkdoc a go/parser
 * that rejects syntax this module uses ("failed to parse package file"). gomarkdoc and `go list` run
 * with GOTOOLCHAIN set to the module's toolchain instead. The query itself runs with GOTOOLCHAIN=auto
 * so that a GOTOOLCHAIN in the environment cannot pin an older go than the module needs.
 */
function moduleToolchain() {
  const version = execFileSync('go', ['env', 'GOVERSION'], {
    cwd: root,
    encoding: 'utf-8',
    env: { ...process.env, GOTOOLCHAIN: 'auto' },
  }).trim();
  // A local build can carry a suffix (go1.27.3-X:nodwarf5); GOTOOLCHAIN takes the release name.
  const name = version.match(/^go[0-9]+(?:\.[0-9]+)*(?:(?:rc|beta)[0-9]+)?/)?.[0];
  if (!name) throw new Error(`docs-gen: cannot read a Go toolchain name from "go env GOVERSION": ${JSON.stringify(version)}`);
  return name;
}

function goPackages(env) {
  const out = execFileSync('go', ['list', '-f', '{{if .GoFiles}}{{.Dir}}{{end}}', './...'], { cwd: root, encoding: 'utf-8', env });
  return out.split('\n').filter(Boolean).map((dir) => './' + toPosix(relative(root, dir)));
}

/**
 * Turns gomarkdoc's escaped backtick pairs back into code spans. A Go doc comment that writes
 * `name` reaches gomarkdoc as plain text, which escapes the backticks (\`) and the Markdown
 * punctuation between them (\-, \(, \{ ...), so the page showed literal backticks. A pair on one
 * line becomes a code span with the backslash escapes inside it removed, since a code span shows
 * its text verbatim. Only text outside code fences is passed in; an unpaired \` stays as it is.
 */
function codeSpans(text) {
  return text.replace(/\\`((?:[^`\\\n]|\\[^`\n])+?)\\`/g, (_, inner) => '`' + inner.replace(/\\([^\n])/g, '$1') + '`');
}

/**
 * Escapes gomarkdoc's Markdown for VitePress, which compiles every page as a Vue template: `{{`
 * outside code would be an interpolation. gomarkdoc writes braces in prose as `\{` and `\}`, so both
 * spellings become HTML entities. Code fences and code spans are left alone (VitePress does not
 * interpolate inside them).
 */
function escapeVue(text) {
  const braces = (s) => s.replace(/\\?\{/g, '&#123;').replace(/\\?\}/g, '&#125;');
  return text
    .split(/(^```[\s\S]*?^```$)/m)
    .map((part, i) =>
      i % 2
        ? part
        : codeSpans(part)
            .split(/(`[^`\n]*`)/)
            .map((s, j) => (j % 2 ? s : braces(s)))
            .join(''),
    )
    .join('');
}

function generateGo() {
  rmSync(goDir, { recursive: true, force: true });
  mkdirSync(goDir, { recursive: true });
  const toolchain = moduleToolchain();
  const env = { ...process.env, GOTOOLCHAIN: toolchain };
  const packages = goPackages(env);
  console.log(`Generating the Go API reference for ${packages.length} packages with gomarkdoc ${gomarkdocVersion} built by ${toolchain}...`);
  const started = Date.now();
  execFileSync(
    'go',
    [
      'run',
      `github.com/princjef/gomarkdoc/cmd/gomarkdoc@${gomarkdocVersion}`,
      '--repository.url', repositoryUrl,
      '--repository.default-branch', defaultBranch,
      '--repository.path', '/',
      '--output', join(goDir, '{{.Dir}}', 'index.md'),
      ...packages,
    ],
    { cwd: root, stdio: 'inherit', env },
  );
  console.log(`gomarkdoc took ${((Date.now() - started) / 1000).toFixed(1)} s.`);

  const found = [];
  const walk = (dir) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const path = join(dir, entry.name);
      if (entry.isDirectory()) walk(path);
      else if (entry.name === 'index.md' && dir !== goDir) found.push({ path, dir: toPosix(relative(goDir, dir)) });
    }
  };
  walk(goDir);
  // Package pages get the same front matter as the other generated pages: no edit link.
  for (const { path } of found) writeFileSync(path, `---\neditLink: false\n---\n\n${escapeVue(readFileSync(path, 'utf-8'))}`);
  const pkgs = found.map((p) => ({ ...p, summary: goSummary(p.path), group: goGroup(p.dir) })).sort((a, b) => a.dir.localeCompare(b.dir));

  const groups = ['Commands', 'Packages', 'Test suites'];
  const sections = groups
    .map((name) => {
      const items = pkgs.filter((p) => p.group === name);
      if (!items.length) return '';
      const lines = items.map((p) => `- [\`${p.dir}\`](/api-reference/go/${p.dir}/)${p.summary ? `: ${prose(p.summary)}.` : ''}`);
      return `## ${name}\n\n${lines.join('\n')}`;
    })
    .filter(Boolean)
    .join('\n\n');
  write(
    join(goDir, 'index.md'),
    `${marker}\n\n# Go API reference\n\nThe exported identifiers of every Go package in the module \`${modulePath}\`, generated from the source comments by [gomarkdoc](https://github.com/princjef/gomarkdoc). Commands live under \`cmd/\` and packages under \`internal/\`, which other Go modules cannot import: the pages are for people who read or extend Parkana. To drive Parkana from your own code, use the [HTTP API](/api-reference/http/). The Grafana SQL datasource in \`grafana/parkana-datasource\` is a separate Go module and is not listed here; see [Grafana SQL datasource](/grafana-datasource).\n\n${sections}\n`,
  );
  return pkgs;
}

/** Commands are under cmd/; test suites are helper packages named *test (objstoretest, plantest). */
function goGroup(dir) {
  if (dir.startsWith('cmd/')) return 'Commands';
  if (dir.split('/').pop().endsWith('test')) return 'Test suites';
  return 'Packages';
}

// The first sentence of the package comment, which gomarkdoc prints right after the import block.
function goSummary(file) {
  const text = readFileSync(file, 'utf-8');
  const after = text.split('```\n\n')[1] ?? '';
  const first = (after.split('\n\n')[0] ?? '').replace(/\\(.)/g, '$1').replace(/\s+/g, ' ').trim();
  if (first.startsWith('#') || first.startsWith('<')) return '';
  const end = first.search(/\.(\s|$)/);
  return end === -1 ? first : first.slice(0, end);
}

// ---------------------------------------------------------------------------------------------

const http = generateHTTP();
const pkgs = generateGo();
if (!pkgs.length) {
  console.error('gomarkdoc produced no packages');
  process.exit(1);
}
write(
  join(apiDir, 'index.md'),
  `${marker}\n\n# API reference\n\n- [HTTP API reference](/api-reference/http/): every route of the Parkana server and its schemas.\n- [Go API reference](/api-reference/go/): every Go package in the module.\n\nThese pages are generated from the OpenAPI document and the Go source on every build.\n`,
);
console.log(`Wrote ${http.opCount} HTTP operations on ${http.pages.length + 2} pages and ${pkgs.length} Go package pages.`);
