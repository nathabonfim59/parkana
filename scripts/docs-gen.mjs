#!/usr/bin/env node
/**
 * Generates the API reference pages from their sources of truth:
 *
 * - docs/api-reference/http/  from the OpenAPI document api/parkana.yaml
 * - docs/api-reference/go/    from the Go source, with gomarkdoc
 *
 * The output is gitignored: `npm run docs:build` (and CI) regenerate it before every build, so it can
 * never drift from the spec or the code. Hand-written pages are the repository's Markdown, read in
 * place; see scripts/doc-links.mjs.
 */
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse as parseYAML } from 'yaml';
import { defaultBranch, httpTags, repositoryUrl } from './doc-links.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const apiDir = join(root, 'docs', 'api-reference');
const httpDir = join(apiDir, 'http');
const goDir = join(apiDir, 'go');
const specFile = 'api/parkana.yaml';
const modulePath = 'github.com/nathabonfim59/parkana';

const gomarkdocVersion = 'v1.1.0';
// Generated pages have no source Markdown to edit, so they hide the edit link.
const marker = '---\neditLink: false\n---\n\n<!-- Generated by npm run docs:api from the OpenAPI document and the Go source. -->';

const toPosix = (p) => p.split('\\').join('/');
const write = (path, text) => {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, text.replace(/\n{3,}/g, '\n\n').trimEnd() + '\n');
};

// ---------------------------------------------------------------------------------------------
// Markdown helpers

/** Escapes text for VitePress (Vue templates) outside code spans. */
function prose(text) {
  return String(text ?? '')
    .split(/(`[^`]*`)/)
    .map((part, i) => (i % 2 ? part : part.replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/\{\{/g, '&#123;&#123;')))
    .join('')
    .trim();
}

/** One table cell: a single line with escaped pipes. */
const cell = (text) => prose(text).replace(/\s*\n\s*/g, ' ').replace(/\|/g, '\\|');

const table = (head, rows) =>
  rows.length
    ? [`| ${head.join(' | ')} |`, `|${head.map(() => '---').join('|')}|`, ...rows.map((r) => `| ${r.join(' | ')} |`)].join('\n')
    : '';

/** A fenced code block whose fence is longer than any backtick run in the text. */
function fence(lang, text) {
  const longest = Math.max(2, ...[...String(text).matchAll(/`+/g)].map((m) => m[0].length));
  const f = '`'.repeat(longest + 1);
  return `${f}${lang}\n${String(text).replace(/\n$/, '')}\n${f}`;
}

