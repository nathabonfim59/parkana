// HTTP API reference

const schemasPage = 'schemas';
const schemaPrefix = '#/components/schemas/';
const responsePrefix = '#/components/responses/';
const responseAnchor = (name) => `response-${name}`;

/** The OpenAPI document and the rules for linking its components. */
class Spec {
  constructor(file) {
    this.file = file;
    this.doc = parseYAML(readFileSync(join(root, file), 'utf-8'));
    this.checkRefs(this.doc, '');
  }

  /** Fails on the first $ref anywhere in the document that does not resolve. */
  checkRefs(node, at) {
    if (Array.isArray(node)) return node.forEach((n, i) => this.checkRefs(n, `${at}/${i}`));
    if (!node || typeof node !== 'object') return;
    if (typeof node.$ref === 'string') this.ref(node.$ref, at);
    // `at` is a JSON pointer, so "/" in path keys is escaped as "~1".
    for (const [k, v] of Object.entries(node)) if (k !== '$ref') this.checkRefs(v, `${at}/${k.replace(/~/g, '~0').replace(/\//g, '~1')}`);
  }

  ref(ref, at = '') {
    if (!ref.startsWith('#/')) throw new Error(`${this.file}: ${at}: only local $refs are supported, got ${ref}`);
    let node = this.doc;
    for (const p of ref.slice(2).split('/')) node = node?.[p.replace(/~1/g, '/').replace(/~0/g, '~')];
    if (node === undefined) throw new Error(`${this.file}: ${at}: unresolved $ref ${ref}`);
    return node;
  }

  deref(node) {
    const seen = new Set();
    while (node && node.$ref) {
      if (seen.has(node.$ref)) throw new Error(`${this.file}: $ref cycle at ${node.$ref}`);
      seen.add(node.$ref);
      node = this.ref(node.$ref);
    }
    return node;
  }

  /**
   * Resolves a parameter, request body or response that may be a Reference Object. OpenAPI 3.1 lets
   * a summary and a description next to $ref override the target's, so a shared response such as
   * LokiError can carry status-specific text at each use.
   */
  resolve(node) {
    if (!node?.$ref) return node;
    const out = { ...this.deref(node) };
    for (const key of ['summary', 'description']) if (node[key] !== undefined) out[key] = node[key];
    return out;
  }

  schemaLink(name, fromPage) {
    const href = fromPage === schemasPage ? `#${name}` : `/api-reference/http/${schemasPage}#${name}`;
    return `[${name}](${href})`;
  }

  responseLink(name, fromPage) {
    const anchor = responseAnchor(name);
    const href = fromPage === schemasPage ? `#${anchor}` : `/api-reference/http/${schemasPage}#${anchor}`;
    return `[${name}](${href})`;
  }

  /** Short type expression for a schema, with links to named schemas. */
  type(schema, fromPage) {
    if (!schema) return 'any';
    if (schema.$ref) {
      const name = schema.$ref.split('/').pop();
      return schema.$ref.startsWith(schemaPrefix) ? this.schemaLink(name, fromPage) : name;
    }
    if (schema.const !== undefined) return `\`${JSON.stringify(schema.const)}\``;
    for (const key of ['oneOf', 'anyOf']) if (schema[key]) return schema[key].map((s) => this.type(s, fromPage)).join(' or ');
    if (schema.allOf) return schema.allOf.map((s) => this.type(s, fromPage)).join(' and ');
    if (Array.isArray(schema.type)) return schema.type.map((t) => this.type({ ...schema, type: t }, fromPage)).join(' or ');
    switch (schema.type) {
      case 'array':
        return `${this.type(schema.items, fromPage)}[]`;
      case 'object':
        if (schema.additionalProperties && typeof schema.additionalProperties === 'object' && !schema.properties) {
          return `map of ${this.type(schema.additionalProperties, fromPage)}`;
        }
        return 'object';
      case undefined:
        return schema.properties ? 'object' : 'any';
      default:
        return schema.format ? `${schema.type} (${schema.format})` : schema.type;
    }
  }

  /** Extra facts for the description column: enum values, default, bounds. */
  facts(schema) {
    const out = [];
    const s = this.deref(schema) ?? {};
    const enumValues = s.enum ?? (s.oneOf ?? s.anyOf ?? []).flatMap((x) => this.deref(x)?.enum ?? []);
    if (enumValues.length) out.push(`One of ${enumValues.map((v) => `\`${JSON.stringify(v)}\``).join(', ')}.`);
    if (schema.default !== undefined) out.push(`Default \`${JSON.stringify(schema.default)}\`.`);
    const bounds = [];
    if (s.minimum !== undefined) bounds.push(`min ${s.minimum}`);
    if (s.maximum !== undefined) bounds.push(`max ${s.maximum}`);
    if (s.minLength !== undefined) bounds.push(`min length ${s.minLength}`);
    if (s.maxLength !== undefined) bounds.push(`max length ${s.maxLength}`);
    if (s.pattern) bounds.push(`pattern \`${s.pattern}\``);
    if (bounds.length) {
      const b = bounds.join(', ');
      out.push(b[0].toUpperCase() + b.slice(1) + '.');
    }
    return out.join(' ');
  }

  /** Field rows of an object schema; inline nested objects get dotted names. */
  fieldRows(schema, fromPage, prefix = '', depth = 0) {
    const s = schema.$ref ? null : schema;
    if (!s) return [];
    const merged = { properties: {}, required: [] };
    for (const part of [s, ...(s.allOf ?? []).map((x) => this.deref(x))]) {
      Object.assign(merged.properties, part.properties ?? {});
      merged.required.push(...(part.required ?? []));
    }
    const rows = [];
    for (const [name, prop] of Object.entries(merged.properties)) {
      const full = prefix + name;
      const desc = [prop.description, this.facts(prop)].filter(Boolean).join(' ');
      rows.push([`\`${full}\``, cell(this.type(prop, fromPage)), merged.required.includes(name) ? 'yes' : '', cell(desc)]);
      if (depth < 3 && !prop.$ref) {
        if (prop.type === 'object' && prop.properties) rows.push(...this.fieldRows(prop, fromPage, `${full}.`, depth + 1));
        if (prop.type === 'array' && prop.items && !prop.items.$ref && prop.items.properties) {
          rows.push(...this.fieldRows(prop.items, fromPage, `${full}[].`, depth + 1));
        }
      }
    }
    return rows;
  }

  fieldsTable(schema, fromPage) {
    return table(['Field', 'Type', 'Required', 'Description'], this.fieldRows(schema, fromPage));
  }

  /** Every operation, with its tag checked against the fixed page list. */
  operations() {
    const known = new Set(httpTags.map((t) => t.tag));
    const ops = [];
    for (const [path, item] of Object.entries(this.doc.paths ?? {})) {
      for (const method of ['get', 'put', 'post', 'patch', 'delete', 'head', 'options']) {
        const op = item[method];
        if (!op) continue;
        const where = `${this.file}: ${method.toUpperCase()} ${path}`;
        const tag = op.tags?.[0];
        if (!tag) throw new Error(`${where}: no tag; every operation needs one of ${[...known].join(', ')}`);
        if (!known.has(tag)) throw new Error(`${where}: tag ${JSON.stringify(tag)} is not one of ${[...known].join(', ')} (scripts/doc-links.mjs httpTags)`);
        if (!op.operationId) throw new Error(`${where}: no operationId`);
        const params = [...(item.parameters ?? []), ...(op.parameters ?? [])].map((p) => this.resolve(p));
        ops.push({ path, method: method.toUpperCase(), op, params, tag });
      }
    }
    return ops;
  }

  /** The body cell of a response: each media type with its schema, or the shared response it is. */
  responseBodies(response, fromPage) {
    const r = this.deref(response);
    const bodies = Object.entries(r.content ?? {}).map(([media, c]) => `\`${media}\`${c.schema ? ' ' + this.type(c.schema, fromPage) : ''}`);
    if (response.$ref?.startsWith(responsePrefix)) bodies.push(`see ${this.responseLink(response.$ref.slice(responsePrefix.length), fromPage)}`);
    return bodies.join(', ');
  }

  renderOperation({ path, method, op, params }, fromPage) {
    const out = [];
    out.push(`## ${prose(op.summary ?? op.operationId)} {#${op.operationId}}`);
    if (op['x-internal']) {
      out.push('**Internal.** Parkana processes call this route on each other; it is not for clients and may change without notice.');
    }
    out.push(fence('http', `${method} ${path}`));
    out.push(`Operation \`${op.operationId}\`.`);
    if (op.deprecated) out.push('**Deprecated.**');
    if (op.description) out.push(prose(op.description));

    if (params.length) {
      out.push('### Parameters');
      out.push(
        table(
          ['Name', 'In', 'Type', 'Required', 'Description'],
          params.map((p) => [
            `\`${p.name}\``,
            p.in,
            cell(this.type(p.schema, fromPage)),
            p.required ? 'yes' : '',
            cell([p.description, p.schema ? this.facts(p.schema) : ''].filter(Boolean).join(' ')),
          ]),
        ),
      );
    }

    const body = op.requestBody && this.resolve(op.requestBody);
    if (body) {
      out.push('### Request body');
      out.push(body.required ? 'Required.' : 'Optional.');
      if (body.description) out.push(prose(body.description));
      for (const [media, content] of Object.entries(body.content ?? {})) {
        const schema = content.schema;
        out.push(`#### \`${media}\``);
        if (schema) out.push(`Type: ${this.type(schema, fromPage)}.`);
        const resolved = schema && this.deref(schema);
        if (resolved && !schema.$ref && (resolved.properties || resolved.allOf)) out.push(this.fieldsTable(resolved, fromPage));
        if (resolved?.description && !schema.$ref) out.push(prose(resolved.description));
        if (content.example !== undefined) {
          const text = typeof content.example === 'string' ? content.example : JSON.stringify(content.example, null, 2);
          out.push(fence(media.includes('json') ? 'json' : 'text', text));
        }
      }
    }

    out.push('### Responses');
    const rows = Object.entries(op.responses ?? {}).map(([status, response]) => [
      `\`${status}\``,
      cell(this.resolve(response).description ?? ''),
      cell(this.responseBodies(response, fromPage)),
    ]);
    out.push(table(['Status', 'Description', 'Body'], rows));
    return out.join('\n\n');
  }

  renderSchemas(fromPage) {
    const out = [];
    const schemas = this.doc.components?.schemas ?? {};
    for (const name of Object.keys(schemas).sort()) {
      const s = schemas[name];
      out.push(`## ${name} {#${name}}`);
      if (s.description) out.push(prose(s.description));
      const fields = s.properties || s.allOf ? this.fieldsTable(s, fromPage) : '';
      if (fields) out.push(fields);
      else {
        out.push(`Type: ${this.type(s, fromPage)}.`);
        const facts = this.facts(s);
        if (facts) out.push(prose(facts));
      }
    }
    return out.join('\n\n');
  }

  renderResponses(fromPage) {
    const out = [];
    const responses = this.doc.components?.responses ?? {};
    for (const name of Object.keys(responses).sort()) {
      const r = this.deref(responses[name]);
      out.push(`### ${name} {#${responseAnchor(name)}}`);
      if (r.description) out.push(prose(r.description));
      const rows = Object.entries(r.content ?? {}).map(([media, c]) => [`\`${media}\``, cell(c.schema ? this.type(c.schema, fromPage) : '')]);
      out.push(table(['Media type', 'Type'], rows));
      for (const c of Object.values(r.content ?? {})) {
        if (c.example !== undefined) out.push(fence('text', typeof c.example === 'string' ? c.example : JSON.stringify(c.example, null, 2)));
      }
    }
    return out.length ? ['## Shared responses', ...out].join('\n\n') : '';
  }
}

function generateHTTP() {
  rmSync(httpDir, { recursive: true, force: true });
  const spec = new Spec(specFile);
  const source = `[\`${specFile}\`](${repositoryUrl}/blob/${defaultBranch}/${specFile})`;
  const ops = spec.operations();

  const pages = [];
  for (const { tag, slug } of httpTags) {
    const tagOps = ops.filter((o) => o.tag === tag);
    if (!tagOps.length) continue;
    const description = spec.doc.tags?.find((t) => t.name === tag)?.description;
    pages.push({ tag, slug, ops: tagOps });
    write(
      join(httpDir, `${slug}.md`),
      [
        marker,
        `# ${tag} {#page-${slug}}`,
        description ? prose(description) : '',
        `Generated from ${source}. Schemas and shared responses are on the [schemas page](/api-reference/http/schemas).`,
        ...tagOps.map((o) => spec.renderOperation(o, slug)),
      ].join('\n\n'),
    );
  }

  write(
    join(httpDir, `${schemasPage}.md`),
    [
      marker,
      '# Schemas',
      `Every schema and shared response of ${source}.`,
      spec.renderSchemas(schemasPage),
      spec.renderResponses(schemasPage),
    ].join('\n\n'),
  );

  // The hand-written companion page, linked once it exists.
  const behavior = existsSync(join(root, 'docs', 'http-api.md'))
    ? ' [HTTP API behavior](/http-api) describes what the schemas cannot: Loki compatibility, limits, streaming and errors.'
    : '';
  const tenantHeader = Object.values(spec.doc.components?.parameters ?? {}).find((p) => p.in === 'header' && /^x-scope-orgid$/i.test(p.name));
  const opRows = (page) =>
    page.ops.map(({ path, method, op }) => [
      `[${cell(op.summary ?? op.operationId)}](/api-reference/http/${page.slug}#${op.operationId})`,
      `\`${method} ${path}\``,
    ]);
  const overview = [
    marker,
    '# HTTP API reference',
    `Parkana serves every route from one HTTP server; which routes a process registers depends on its roles. These pages are generated from the OpenAPI document ${source}.${behavior}`,
    '## Base URL',
    'Paths are relative to the server root, for example `http://localhost:3100`. There is no common prefix: Loki routes live under `/loki/api/v1`, OTLP under `/v1/logs`, and Parkana\'s own routes under `/api/v1`.',
    '## Tenant',
    `Requests name their tenant in the \`X-Scope-OrgID\` header, as in Loki. Without the header the request goes to the \`default\` tenant.${tenantHeader?.description ? ' ' + prose(tenantHeader.description) : ''}`,
    '## Errors',
    'Errors are Loki-style plain text: a `text/plain` body with one message and the HTTP status code, not a JSON envelope. See [LokiError](/api-reference/http/schemas#response-LokiError).',
    '## Operations',
    ...pages.flatMap((p) => [`### ${p.tag}`, table(['Operation', 'Request'], opRows(p))]),
  ];
  write(join(httpDir, 'index.md'), overview.join('\n\n'));
  return { pages, opCount: ops.length };
}

