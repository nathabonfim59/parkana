var update = flag.Bool("update", false, "rewrite the generated metrics table in docs/operations.md")

const (
	operationsPage = "../../docs/operations.md"
	metricsBegin   = "<!-- metrics:begin (generated by make docs-metrics; do not edit) -->"
	metricsEnd     = "<!-- metrics:end -->"
)

// historicalMetricNames are parkana_ names docs/benchmarks.md may use that
// are not registered metrics. A name ending in "_" is a prefix.
// None of them was ever a Prometheus metric: they are result keys that
// scripts/bench-phase3.sh writes into benchmark metadata.
var historicalMetricNames = map[string]bool{
	// The ingest-stage cgroup memory.peak reading.
	"parkana_ingest_memory_peak_bytes": true,
	// The configured container memory limit, recorded next to the peak.
	"parkana_effective_memory_bytes": true,
	// The legacy-arm runtime contract: mode, source and flag support.
	"parkana_runtime_mode":    true,
	"parkana_runtime_source":  true,
	"parkana_runtime_support": true,
	// Prefix of the legacy arm's known always/F1/U1 baseline keys.
	"parkana_legacy_known_": true,
}

// recordingRegisterer forwards to a real registry and keeps every collector
// that is registered and not unregistered again, so a test sees exactly what
// the process exposes.
type recordingRegisterer struct {
	next prometheus.Registerer
	mu   sync.Mutex
	cs   []prometheus.Collector
}

func (r *recordingRegisterer) Register(c prometheus.Collector) error {
	if err := r.next.Register(c); err != nil {
		return err
	}
	r.mu.Lock()
	defer r.mu.Unlock()
	r.cs = append(r.cs, c)
	return nil
}

func (r *recordingRegisterer) MustRegister(cs ...prometheus.Collector) {
	for _, c := range cs {
		if err := r.Register(c); err != nil {
			panic(err)
		}
	}
}

func (r *recordingRegisterer) Unregister(c prometheus.Collector) bool {
	if !r.next.Unregister(c) {
		return false
	}
	r.mu.Lock()
	defer r.mu.Unlock()
	r.cs = slices.DeleteFunc(r.cs, func(x prometheus.Collector) bool { return x == c })
	return true
}

func (r *recordingRegisterer) collectors() []prometheus.Collector {
	r.mu.Lock()
	defer r.mu.Unlock()
	return slices.Clone(r.cs)
}

// metricRow is one line of the metrics table.
type metricRow struct {
	name, kind, help string
	labels           []string
}

// descPattern matches prometheus.Desc.String(), the only way to read a
// Desc's name, help and labels. A client_golang upgrade that changes the
// format fails the test instead of producing a wrong table.
var descPattern = regexp.MustCompile(`^Desc\{fqName: ("(?:[^"\\]|\\.)*"), help: ("(?:[^"\\]|\\.)*"), unit: "(?:[^"\\]|\\.)*", constLabels: \{([^}]*)\}, variableLabels: \{([^}]*)\}\}$`)

func parseDesc(d *prometheus.Desc) (metricRow, error) {
	if err := d.Err(); err != nil {
		return metricRow{}, err
	}
	m := descPattern.FindStringSubmatch(d.String())
	if m == nil {
		return metricRow{}, fmt.Errorf("unrecognized Desc format %s", d)
	}
	name, err := strconv.Unquote(m[1])
	if err != nil {
		return metricRow{}, err
	}
	help, err := strconv.Unquote(m[2])
	if err != nil {
		return metricRow{}, err
	}
	var labels []string
	// Constant labels print as name="value"; the table lists their names,
	// because one metric can be registered once per role with a different
	// value (the pipeline metrics' role label).
	for l := range strings.SplitSeq(m[3], ",") {
		if l != "" {
			name, _, _ := strings.Cut(l, "=")
			labels = append(labels, name)
		}
	}
	for l := range strings.SplitSeq(m[4], ",") {
		if l == "" {
			continue
		}
		// A constrained variable label prints as c(name).
		if inner, ok := strings.CutPrefix(l, "c("); ok {
			l = strings.TrimSuffix(inner, ")")
		}
		labels = append(labels, l)
	}
	slices.Sort(labels)
	return metricRow{name: name, help: help, labels: labels}, nil
}

// vecKind is the type of the collector kinds whose type a Desc does not
// carry and that expose nothing before their first labelled observation.
func vecKind(c prometheus.Collector) string {
	switch c.(type) {
	case *prometheus.CounterVec:
		return "counter"
	case *prometheus.GaugeVec:
		return "gauge"
	case *prometheus.HistogramVec:
		return "histogram"
	case *prometheus.SummaryVec:
		return "summary"
	}
	return ""
}

// exercise gives collectors that expose nothing until used one sample each,
// so Gather reports their type: one request through the server's middleware
// for its HTTP metrics, and one build and one skip for the sidecar index
// metrics, a custom collector over vectors.
func exercise(t *testing.T, a *assembly, cs []prometheus.Collector) {
	t.Helper()
	rec := httptest.NewRecorder()
	a.srv.Handler().ServeHTTP(rec, httptest.NewRequest(http.MethodGet, "/ready", nil))
	for _, c := range cs {
		if m, ok := c.(*index.Metrics); ok {
			m.ObserveBuild(index.SourceIngest, time.Millisecond, 1)
			m.ObserveSkip(index.SourceIngest, time.Millisecond)
		}
	}
}

// collectMetrics assembles the all-in-one process and returns one row per
// exposed parkana metric, sorted by name: every collector registered on
// Deps.Metrics (read from its Descs) and every family the server's registry
// gathers (the server registers its own HTTP metrics there directly). Go
// runtime and process metrics are left out.
func collectMetrics(t *testing.T) []metricRow {
	t.Helper()
	reg := prometheus.NewRegistry()
	rec := &recordingRegisterer{next: reg}
	a := assembleForTest(t, rec, reg, "-roles=all")
	cs := rec.collectors()
	exercise(t, a, cs)

	families, err := reg.Gather()
	if err != nil {
		t.Fatalf("gather: %v", err)
	}
	gathered := make(map[string]metricRow, len(families))
	for _, f := range families {
		row := metricRow{name: f.GetName(), kind: strings.ToLower(f.GetType().String()), help: f.GetHelp()}
		if ms := f.GetMetric(); len(ms) > 0 {
			for _, lp := range ms[0].GetLabel() {
				row.labels = append(row.labels, lp.GetName())
			}
			slices.Sort(row.labels)
		}
		gathered[row.name] = row
	}

	rows := make(map[string]metricRow)
	for _, c := range cs {
		ch := make(chan *prometheus.Desc, 64)
		go func() { c.Describe(ch); close(ch) }()
		for d := range ch {
			row, err := parseDesc(d)
			if err != nil {
				t.Errorf("collector %T: %v", c, err)
				continue
			}
			row.kind = vecKind(c)
			if row.kind == "" {
				row.kind = gathered[row.name].kind
			}
			if row.kind == "" {
				t.Errorf("metric %s (%T) has no type: it exposes no sample after assembly; give it one in exercise", row.name, c)
			}
			// The same name from another collector (one per role) must
			// describe the same metric, or one table row would hide the other.
			if prev, ok := rows[row.name]; ok && (prev.kind != row.kind || prev.help != row.help || !slices.Equal(prev.labels, row.labels)) {
				t.Errorf("metric %s is registered twice with different help, type or labels: %+v and %+v", row.name, prev, row)
			}
			rows[row.name] = row
		}
	}
	for name, row := range gathered {
		if _, ok := rows[name]; ok {
			continue
		}
		if strings.HasPrefix(name, "go_") || strings.HasPrefix(name, "process_") {
			continue
		}
		rows[name] = row
	}
	return slices.SortedFunc(maps.Values(rows), func(a, b metricRow) int { return strings.Compare(a.name, b.name) })
}

// renderMetrics renders the rows as the Markdown table of docs/operations.md.
func renderMetrics(rows []metricRow) string {
	var b strings.Builder
	b.WriteString("| Metric | Type | Labels | Description |\n|---|---|---|---|\n")
	for _, r := range rows {
		labels := make([]string, len(r.labels))
		for i, l := range r.labels {
			labels[i] = "`" + l + "`"
		}
		help := strings.ReplaceAll(r.help, "|", `\|`)
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s |\n", r.name, r.kind, strings.Join(labels, ", "), help)
	}
	return b.String()
}

// TestMetricsReference keeps docs/operations.md, the metric names in the
// hand-written pages and the registered collectors in step. With -update
// (make docs-metrics) it rewrites the generated table instead of comparing.
func TestMetricsReference(t *testing.T) {
	rows := collectMetrics(t)
	table := renderMetrics(rows)

	page, err := os.ReadFile(operationsPage)
	if err != nil {
		t.Fatal(err)
	}
	head, rest, ok := bytes.Cut(page, []byte(metricsBegin))
	if !ok {
		t.Fatalf("%s: missing %q", operationsPage, metricsBegin)
	}
	current, tail, ok := bytes.Cut(rest, []byte(metricsEnd))
	if !ok {
		t.Fatalf("%s: missing %q", operationsPage, metricsEnd)
	}
	want := "\n" + table
	if *update {
		out := slices.Concat(head, []byte(metricsBegin+want), []byte(metricsEnd), tail)
		if err := os.WriteFile(operationsPage, out, 0o644); err != nil {
			t.Fatal(err)
		}
	} else if string(current) != want {
		t.Errorf("%s: the metrics table is out of date; run make docs-metrics", operationsPage)
		reportLineDiff(t, string(current), want)
	}

	t.Run("source names", func(t *testing.T) { checkSourceNames(t, rows) })
	t.Run("doc mentions", func(t *testing.T) { checkDocMentions(t, rows) })
}

// reportLineDiff logs the lines only one of the two texts has, so a stale
// table names the rows that differ instead of printing both tables.
func reportLineDiff(t *testing.T, got, want string) {
	t.Helper()
	gotLines := strings.Split(got, "\n")
	wantLines := strings.Split(want, "\n")
	for _, l := range wantLines {
		if !slices.Contains(gotLines, l) {
			t.Logf("missing from the page: %s", l)
		}
	}
	for _, l := range gotLines {
		if !slices.Contains(wantLines, l) {
			t.Logf("on the page but not generated: %s", l)
		}
	}
}

// metricOptName matches a metric name literal in collector options.
var metricOptName = regexp.MustCompile(`Name:\s*"(parkana_[a-z0-9_]+)"`)

// checkSourceNames fails when a metric name written in the code's collector
// options is not in the table, which is how a metric registered after
// assembly (lazily, per tenant) would show up.
func checkSourceNames(t *testing.T, rows []metricRow) {
	known := make(map[string]bool, len(rows))
	for _, r := range rows {
		known[r.name] = true
	}
	for _, root := range []string{"../../internal", "."} {
		err := filepath.WalkDir(root, func(path string, d fs.DirEntry, err error) error {
			if err != nil || d.IsDir() || !strings.HasSuffix(path, ".go") || strings.HasSuffix(path, "_test.go") {
				return err
			}
			src, err := os.ReadFile(path)
			if err != nil {
				return err
			}
			for _, m := range metricOptName.FindAllSubmatch(src, -1) {
				if name := string(m[1]); !known[name] {
					t.Errorf("%s names metric %s, which the assembled process does not register", path, name)
				}
			}
			return nil
		})
		if err != nil {
			t.Fatal(err)
		}
	}
}

// docMetricName matches a parkana metric name in prose. Metric names start
// with a letter after the prefix, which skips file names such as
// parkana_1.0.0-1_amd64.deb; \b skips names inside longer identifiers. A
// trailing * marks a prefix (parkana_upload_*).
var docMetricName = regexp.MustCompile(`\bparkana_[a-z][a-z0-9_]*\*?`)

// checkDocMentions fails when a hand-written page names a parkana metric
// that is not registered. Histogram and summary names also count with the
// _bucket, _sum and _count suffixes Prometheus exposes them with; counters
// are registered with their _total suffix, so no suffix is added for them.
func checkDocMentions(t *testing.T, rows []metricRow) {
	valid := make(map[string]bool)
	for _, r := range rows {
		valid[r.name] = true
		switch r.kind {
		case "histogram":
			valid[r.name+"_bucket"] = true
			fallthrough
		case "summary":
			valid[r.name+"_sum"] = true
			valid[r.name+"_count"] = true
		}
	}
	pages := docPages(t)
	pages = append(pages, "../../README.md", "../../grafana/parkana-datasource/README.md")
	for _, page := range pages {
		src, err := os.ReadFile(page)
		if err != nil {
			t.Fatal(err)
		}
		allowed := map[string]bool{}
		if filepath.Base(page) == "benchmarks.md" {
			allowed = historicalMetricNames
		}
		n := 0
		for line := range strings.SplitSeq(string(src), "\n") {
			n++
			for _, name := range docMetricName.FindAllString(line, -1) {
				ok := valid[name] || allowed[name]
				if prefix, isPrefix := strings.CutSuffix(name, "*"); isPrefix {
					ok = allowed[prefix] || anyHasPrefix(valid, prefix)
				}
				if !ok {
					t.Errorf("%s:%d names %s, which is not a registered metric", page, n, name)
				}
			}
		}
	}
}

// docPages returns every Markdown file under docs/, section subpages
// included, except the generated docs/api-reference/ and the raw benchmark
// results under docs/benchmarks/.
func docPages(t *testing.T) []string {
	t.Helper()
	const docs = "../../docs"
	var pages []string
	err := filepath.WalkDir(docs, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() && (path == filepath.Join(docs, "api-reference") || path == filepath.Join(docs, "benchmarks")) {
			return filepath.SkipDir
		}
		if !d.IsDir() && filepath.Ext(path) == ".md" {
			pages = append(pages, path)
		}
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	return pages
}

func anyHasPrefix(names map[string]bool, prefix string) bool {
	for name := range names {
		if strings.HasPrefix(name, prefix) {
			return true
		}
	}
	return false
}
