var update = flag.Bool("update", false, "rewrite the generated flag reference in docs/configuration.md")

// repoRoot is the repository root relative to this package's directory,
// where go test runs.
const repoRoot = "../.."

const (
	flagsBegin = "<!-- flags:begin (generated by make docs-flags; do not edit) -->"
	flagsEnd   = "<!-- flags:end -->"
)

// flagGroups are the "### " sections of the flag reference, in page order.
// A match entry ending in "." is a name prefix; any other entry is an exact
// flag name. Every flag must match exactly one group.
var flagGroups = []struct {
	heading string
	match   []string
}{
	{"Roles, HTTP and logging", []string{"roles", "http.", "log.", "multi-tenant"}},
	{"Storage and catalog", []string{"catalog.", "data.dir", "storage."}},
	{"Streams", []string{"stream."}},
	{"Ingest", []string{"ingest."}},
	{"WAL", []string{"wal."}},
	{"Search sidecars", []string{"index."}},
	{"Querier", []string{"querier."}},
	{"LogQL limits", []string{"logql."}},
	{"Live tail", []string{"tail."}},
	{"Pipelines", []string{"pipeline."}},
	{"SQL endpoint", []string{"sql."}},
	{"Compactor", []string{"compactor."}},
}

// flags returns every flag parse registers, sorted by name.
func flags() []*flag.Flag {
	fs, _ := newFlagSet(new(Config))
	var out []*flag.Flag
	fs.VisitAll(func(f *flag.Flag) { out = append(out, f) })
	return out
}

// renderFlagReference renders the generated block of the flag reference:
// one table per flag group, flags sorted by name.
func renderFlagReference(all []*flag.Flag) (string, error) {
	groups := make([][]*flag.Flag, len(flagGroups))
	var errs []string
	for _, f := range all {
		var in []int
		for i, g := range flagGroups {
			if slices.ContainsFunc(g.match, func(m string) bool {
				return m == f.Name || strings.HasSuffix(m, ".") && strings.HasPrefix(f.Name, m)
			}) {
				in = append(in, i)
			}
		}
		switch len(in) {
		case 0:
			errs = append(errs, fmt.Sprintf("flag -%s is in no group: add it to flagGroups in internal/config/docref_test.go", f.Name))
		case 1:
			groups[in[0]] = append(groups[in[0]], f)
		default:
			errs = append(errs, fmt.Sprintf("flag -%s matches %d groups in flagGroups", f.Name, len(in)))
		}
	}
	var b strings.Builder
	b.WriteString(flagsBegin + "\n")
	for i, g := range flagGroups {
		if len(groups[i]) == 0 {
			errs = append(errs, fmt.Sprintf("flag group %q has no flags: remove it from flagGroups", g.heading))
			continue
		}
		fmt.Fprintf(&b, "\n### %s\n\n", g.heading)
		b.WriteString("| flag | environment variable | default | description |\n|---|---|---|---|\n")
		for _, f := range groups[i] {
			def := ""
			if !slices.Contains([]string{"", "0", "0s", "false"}, f.DefValue) {
				def = "`" + f.DefValue + "`"
			}
			fmt.Fprintf(&b, "| `-%s` | `%s` | %s | %s |\n", f.Name, EnvName(f.Name), def, strings.ReplaceAll(f.Usage, "|", `\|`))
		}
	}
	b.WriteString("\n" + flagsEnd)
	if len(errs) > 0 {
		return "", fmt.Errorf("%s", strings.Join(errs, "\n"))
	}
	return b.String(), nil
}

// TestFlagReference checks that the flag tables in docs/configuration.md
// match the flags parse registers. Run make docs-flags (go test with
// -update) to rewrite them.
func TestFlagReference(t *testing.T) {
	want, err := renderFlagReference(flags())
	if err != nil {
		t.Fatal(err)
	}
	path := filepath.Join(repoRoot, "docs", "configuration.md")
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	page := string(data)
	start := strings.Index(page, flagsBegin)
	end := strings.Index(page, flagsEnd)
	if start < 0 || end < start {
		t.Fatalf("%s: no %q ... %q block", path, flagsBegin, flagsEnd)
	}
	got := page[start : end+len(flagsEnd)]
	if got == want {
		return
	}
	if *update {
		page = page[:start] + want + page[end+len(flagsEnd):]
		if err := os.WriteFile(path, []byte(page), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	gotLines, wantLines := strings.Split(got, "\n"), strings.Split(want, "\n")
	for i := range max(len(gotLines), len(wantLines)) {
		g, w := lineAt(gotLines, i), lineAt(wantLines, i)
		if g != w {
			t.Fatalf("%s: flag reference is out of date (run make docs-flags); first difference in the block, line %d:\n got: %s\nwant: %s", path, i+1, g, w)
		}
	}
}

func lineAt(lines []string, i int) string {
	if i < len(lines) {
		return lines[i]
	}
	return "<end of block>"
}

// nonFlagEnv lists the PARKANA_ variables the pages may name that are not
// flags. An entry ending in "_" covers every variable with that prefix.
var nonFlagEnv = []string{
	// Integration tests: PARKANA_TEST_S3_ENDPOINT, PARKANA_TEST_POSTGRES_DSN.
	"PARKANA_TEST_",
	// packaging/nfpm.yaml, set by make packages.
	"PARKANA_VERSION",
	"PARKANA_ARCH",
	// deploy/compose: host ports, the dev Garage key, the log generator.
	"PARKANA_HTTP_PORT",
	"PARKANA_S3_PORT",
	"PARKANA_DEV_GARAGE_KEY_",
	"PARKANA_GENERATOR_",
	// Scripts: deploy/compose/validate*.sh, scripts/e2e-*.sh,
	// scripts/bench-*.sh.
	"PARKANA_VALIDATE_",
	"PARKANA_E2E_",
	"PARKANA_OTLP_E2E_",
	"PARKANA_BENCH_",
	// Read by skills/parkana/scripts/parkana-query.sh, not by parkana.
	"PARKANA_URL",
	"PARKANA_CURL_CONFIG",
	"PARKANA_MAX_WINDOW",
}

var (
	envMention = regexp.MustCompile(`PARKANA_[A-Z0-9_]+`)
	// flagToken is one whitespace-separated word of code that starts a
	// flag: optional opening quotes or brackets, one or two dashes, the
	// name, then "=value" or closing punctuation.
	flagToken = regexp.MustCompile(`^["'(\[{]*--?([a-z][a-z0-9-]*(?:\.[a-z0-9-]+)*)(?:=.*|["'),;:.\]}]*)$`)
)

// mentionPages returns the hand-written pages checked for mentions, relative
// to the repository root: every Markdown file under docs/, section subpages
// included (not the generated docs/api-reference/ or the raw results under
// docs/benchmarks/), README.md, the Grafana plugin's README (a site page),
// and the Markdown and env files under deploy/ and packaging/.
func mentionPages(t *testing.T) []string {
	t.Helper()
	var pages []string
	docs := filepath.Join(repoRoot, "docs")
	err := filepath.WalkDir(docs, func(path string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() && (path == filepath.Join(docs, "api-reference") || path == filepath.Join(docs, "benchmarks")) {
			return filepath.SkipDir
		}
		if !d.IsDir() && filepath.Ext(path) == ".md" {
			pages = append(pages, path)
		}
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	pages = append(pages,
		filepath.Join(repoRoot, "README.md"),
		filepath.Join(repoRoot, "grafana", "parkana-datasource", "README.md"))
	for _, dir := range []string{"deploy", "packaging"} {
		err := filepath.WalkDir(filepath.Join(repoRoot, dir), func(path string, d os.DirEntry, err error) error {
			if err != nil {
				return err
			}
			if ext := filepath.Ext(path); !d.IsDir() && (ext == ".md" || ext == ".env") {
				pages = append(pages, path)
			}
			return nil
		})
		if err != nil {
			t.Fatal(err)
		}
	}
	return pages
}

// codeLines returns, for each line of a page, the text of it that is code:
// the whole line inside a fenced block or in a file that is not Markdown,
// the inline code spans otherwise.
func codeLines(path, text string) [][]string {
	lines := strings.Split(text, "\n")
	out := make([][]string, len(lines))
	if filepath.Ext(path) != ".md" {
		for i, l := range lines {
			out[i] = []string{l}
		}
		return out
	}
	fence := ""
	for i, l := range lines {
		trimmed := strings.TrimLeft(l, " ")
		switch {
		case fence != "":
			if strings.HasPrefix(trimmed, fence) && strings.Trim(trimmed, fence[:1]) == "" {
				fence = ""
			} else {
				out[i] = []string{l}
			}
		case strings.HasPrefix(trimmed, "```") || strings.HasPrefix(trimmed, "~~~"):
			fence = trimmed[:len(trimmed)-len(strings.TrimLeft(trimmed, trimmed[:1]))]
		default:
			out[i] = codeSpans(l)
		}
	}
	return out
}

// codeSpans returns the contents of the inline code spans in line: a run of
// n backticks up to the next run of exactly n backticks.
func codeSpans(line string) []string {
	var spans []string
	for {
		start := strings.IndexByte(line, '`')
		if start < 0 {
			return spans
		}
		n := len(line[start:]) - len(strings.TrimLeft(line[start:], "`"))
		rest := line[start+n:]
		found := false
		for off := 0; ; {
			j := strings.IndexByte(rest[off:], '`')
			if j < 0 {
				break
			}
			j += off
			m := len(rest[j:]) - len(strings.TrimLeft(rest[j:], "`"))
			if m == n {
				spans = append(spans, rest[:j])
				line, found = rest[j+m:], true
				break
			}
			off = j + m
		}
		if !found {
			return spans
		}
	}
}

// TestMentions checks that every flag and PARKANA_ variable a hand-written
// page names exists.
//
// A flag mention is a word of code (inline code span, fenced block, or any
// line of an env file) of the form -name or --name, optionally followed by
// =value, where name is dotted ([a-z][a-z0-9-]* followed by one or more
// .part). Every Parkana flag but -roles and -multi-tenant is dotted, and an
// undotted word only counts when it names one of those two, so the
// single-letter and undotted flags of other tools (curl -H, docker -p,
// go test -run) never count. Prose outside code is not checked.
// An environment mention is any PARKANA_[A-Z0-9_]+ anywhere in the page; it
// must be the env name of a flag or match nonFlagEnv.
func TestMentions(t *testing.T) {
	all := flags()
	names := make(map[string]bool, len(all))
	envs := make(map[string]bool, len(all))
	for _, f := range all {
		names[f.Name] = true
		envs[EnvName(f.Name)] = true
	}
	for _, path := range mentionPages(t) {
		data, err := os.ReadFile(path)
		if err != nil {
			t.Fatal(err)
		}
		rel, err := filepath.Rel(repoRoot, path)
		if err != nil {
			t.Fatal(err)
		}
		text := string(data)
		for i, code := range codeLines(path, text) {
			for _, c := range code {
				for word := range strings.FieldsSeq(c) {
					m := flagToken.FindStringSubmatch(word)
					if m == nil || names[m[1]] || !strings.Contains(m[1], ".") {
						continue
					}
					t.Errorf("%s:%d: flag -%s does not exist", rel, i+1, m[1])
				}
			}
		}
		for i, line := range strings.Split(text, "\n") {
			for _, env := range envMention.FindAllString(line, -1) {
				if !knownEnv(env, envs) {
					t.Errorf("%s:%d: %s is neither a flag's environment variable nor in nonFlagEnv", rel, i+1, env)
				}
			}
		}
	}
}

// knownEnv reports whether env, a PARKANA_ name found in a page, is the env
// name of a flag (a key of envs) or matches nonFlagEnv. A name ending in "_"
// is a prefix mention (the page wrote PARKANA_* or PARKANA_STORAGE_S3_*):
// it passes when it starts at least one flag env name or nonFlagEnv entry.
func knownEnv(env string, envs map[string]bool) bool {
	if envs[env] || slices.ContainsFunc(nonFlagEnv, func(a string) bool {
		return a == env || strings.HasSuffix(a, "_") && strings.HasPrefix(env, a)
	}) {
		return true
	}
	if !strings.HasSuffix(env, "_") {
		return false
	}
	prefixes := func(name string) bool { return strings.HasPrefix(name, env) }
	return slices.ContainsFunc(slices.Collect(maps.Keys(envs)), prefixes) || slices.ContainsFunc(nonFlagEnv, prefixes)
}

// TestEnvMentions checks knownEnv on names as pages write them.
func TestEnvMentions(t *testing.T) {
	envs := make(map[string]bool)
	for _, f := range flags() {
		envs[EnvName(f.Name)] = true
	}
	for _, tc := range []struct {
		env  string
		want bool
	}{
		{"PARKANA_STORAGE_S3_BUCKET", true},
		{"PARKANA_TEST_POSTGRES_DSN", true},
		{"PARKANA_VERSION", true},
		{"PARKANA_", true},            // PARKANA_*
		{"PARKANA_STORAGE_S3_", true}, // PARKANA_STORAGE_S3_*
		{"PARKANA_E2E_", true},        // a nonFlagEnv family
		{"PARKANA_DEV_", true},        // prefixes nonFlagEnv's PARKANA_DEV_GARAGE_KEY_
		{"PARKANA_STORAGE_S3_BUCKE", false},
		{"PARKANA_FOO_", false},
		{"PARKANA_FOO_BAR", false},
		{"PARKANA_VERSION_", false},
	} {
		if got := knownEnv(tc.env, envs); got != tc.want {
			t.Errorf("knownEnv(%q) = %v, want %v", tc.env, got, tc.want)
		}
	}
}
