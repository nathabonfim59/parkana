var update = flag.Bool("update", false, "rewrite the generated pattern catalog in docs/pipelines/redaction.md")

const (
	// patternsFile is the single source of the redaction pattern catalog:
	// the parkana-redaction skill reads it and the page block is generated
	// from it.
	patternsFile   = "skills/parkana-redaction/patterns.json"
	redactionPage  = "docs/pipelines/redaction.md"
	patternsBegin  = "<!-- redaction-patterns:begin (generated by make docs-redaction from skills/parkana-redaction/patterns.json; do not edit) -->"
	patternsEnd    = "<!-- redaction-patterns:end -->"
	catalogDataset = "sample"
)

// redactCase is one input line and the line the step must produce.
type redactCase struct {
	In  string `json:"in"`
	Out string `json:"out"`
}

// redactPattern is one catalog entry: a redact step plus its evidence.
type redactPattern struct {
	ID             string       `json:"id"`
	VariantOf      string       `json:"variant_of,omitempty"`
	Finds          string       `json:"finds"`
	Pattern        string       `json:"pattern"`
	Replace        string       `json:"replace"`
	Cases          []redactCase `json:"cases"`
	FalsePositives string       `json:"false_positives"`
}

// redactCatalog is the whole patterns.json document.
type redactCatalog struct {
	Patterns []redactPattern `json:"patterns"`
	Combined struct {
		About string       `json:"about"`
		Cases []redactCase `json:"cases"`
	} `json:"combined"`
	FieldNames struct {
		About   string   `json:"about"`
		Pattern string   `json:"pattern"`
		Match   []string `json:"match"`
		Keep    []string `json:"keep"`
	} `json:"field_names"`
}

// step is the redact step as a user pastes it into a definition. Every
// catalog step drops the entry when the step fails (a bound exceeded):
// on_error keep would restore and store the unredacted value.
type step struct {
	Type    string           `json:"type"`
	Pattern string           `json:"pattern"`
	Replace string           `json:"replace"`
	OnError pipeline.OnError `json:"on_error"`
}

func (p redactPattern) step() step {
	return step{Type: string(pipeline.StepRedact), Pattern: p.Pattern, Replace: p.Replace, OnError: pipeline.OnErrorDrop}
}

func loadRedactCatalog(t *testing.T, root string) redactCatalog {
	t.Helper()
	data, err := os.ReadFile(filepath.Join(root, patternsFile))
	if err != nil {
		t.Fatal(err)
	}
	var c redactCatalog
	if err := json.Unmarshal(data, &c, json.RejectUnknownMembers(true)); err != nil {
		t.Fatalf("%s: %v", patternsFile, err)
	}
	return c
}

// primary returns the patterns that are not variants, in catalog order: the
// recommended full pipeline.
func (c redactCatalog) primary() []redactPattern {
	var out []redactPattern
	for _, p := range c.Patterns {
		if p.VariantOf == "" {
			out = append(out, p)
		}
	}
	return out
}

// applyLines compiles patterns as one ingest pipeline and runs each line
// through it, returning the resulting lines.
func applyLines(t *testing.T, name string, patterns []redactPattern, lines []string) []string {
	t.Helper()
	def := pipeline.Definition{Name: name, Stage: pipeline.StageIngest, Selector: "*"}
	for _, p := range patterns {
		st := p.step()
		def.Steps = append(def.Steps, pipeline.Step{
			Type: pipeline.StepType(st.Type), Pattern: st.Pattern, Replace: new(st.Replace), OnError: st.OnError,
		})
	}
	c, err := pipeline.Compile(def, pipeline.CompileOptions{StreamLabels: []string{"service_name"}})
	if err != nil {
		t.Fatalf("%s: compile: %v", name, err)
	}
	labels := logs.New(logs.Label{Name: "service_name", Value: catalogDataset})
	out := make([]string, 0, len(lines))
	for _, l := range lines {
		e, outcome, err := c.Apply(t.Context(), catalogDataset, pipeline.Entry{Line: l, Labels: labels})
		if err != nil || outcome != pipeline.OutcomeKeep {
			t.Fatalf("%s: apply %q: outcome=%v err=%v", name, l, outcome, err)
		}
		out = append(out, e.Line)
	}
	return out
}

func checkCases(t *testing.T, name string, patterns []redactPattern, cases []redactCase) {
	t.Helper()
	if len(cases) == 0 {
		t.Errorf("%s: no cases", name)
		return
	}
	lines := make([]string, len(cases))
	for i, c := range cases {
		lines[i] = c.In
	}
	for i, got := range applyLines(t, name, patterns, lines) {
		if got != cases[i].Out {
			t.Errorf("%s: %q\n got: %q\nwant: %q", name, cases[i].In, got, cases[i].Out)
		}
	}
}

// TestRedactionPatterns runs every case of patterns.json through the real
// pipeline compiler and executor: each pattern alone, every non-variant
// pattern together in catalog order, and the field-name heuristic.
func TestRedactionPatterns(t *testing.T) {
	c := loadRedactCatalog(t, moduleRoot(t))
	if len(c.Patterns) == 0 {
		t.Fatal("no patterns")
	}
	ids := map[string]bool{}
	for _, p := range c.Patterns {
		if p.ID == "" || ids[p.ID] {
			t.Errorf("pattern id %q is empty or repeated", p.ID)
		}
		ids[p.ID] = true
		if p.Finds == "" || p.FalsePositives == "" {
			t.Errorf("%s: finds and false_positives are required", p.ID)
		}
		for _, s := range []string{p.ID, p.Finds, p.FalsePositives, p.Pattern, p.Replace} {
			if strings.ContainsAny(s, "`\n") {
				t.Errorf("%s: %q holds a backtick or newline, which the generated table cannot show", p.ID, s)
			}
		}
		checkCases(t, p.ID, []redactPattern{p}, p.Cases)
	}
	for _, p := range c.Patterns {
		if p.VariantOf != "" && (!ids[p.VariantOf] || p.VariantOf == p.ID) {
			t.Errorf("%s: variant_of %q is not another pattern", p.ID, p.VariantOf)
		}
	}
	checkCases(t, "combined", c.primary(), c.Combined.Cases)

	re, err := regexp.Compile(c.FieldNames.Pattern)
	if err != nil {
		t.Fatalf("field_names: %v", err)
	}
	for _, n := range c.FieldNames.Match {
		if !re.MatchString(n) {
			t.Errorf("field_names: %q should match", n)
		}
	}
	for _, n := range c.FieldNames.Keep {
		if re.MatchString(n) {
			t.Errorf("field_names: %q should not match", n)
		}
	}
}

// TestRedactionCatalogPage checks that the catalog block of the redaction
// page matches patterns.json. Run make docs-redaction (go test with -update)
// to rewrite it.
func TestRedactionCatalogPage(t *testing.T) {
	root := moduleRoot(t)
	want, err := renderRedactionCatalog(loadRedactCatalog(t, root))
	if err != nil {
		t.Fatal(err)
	}
	path := filepath.Join(root, redactionPage)
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	page := string(data)
	start := strings.Index(page, patternsBegin)
	end := strings.Index(page, patternsEnd)
	if start < 0 || end < start {
		t.Fatalf("%s: no %q ... %q block", path, patternsBegin, patternsEnd)
	}
	got := page[start : end+len(patternsEnd)]
	if got == want {
		return
	}
	if *update {
		page = page[:start] + want + page[end+len(patternsEnd):]
		if err := os.WriteFile(path, []byte(page), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	gotLines, wantLines := strings.Split(got, "\n"), strings.Split(want, "\n")
	for i := range max(len(gotLines), len(wantLines)) {
		g, w := lineAt(gotLines, i), lineAt(wantLines, i)
		if g != w {
			t.Fatalf("%s: pattern catalog is out of date (run make docs-redaction); first difference in the block, line %d:\n got: %s\nwant: %s", path, i+1, g, w)
		}
	}
}

func lineAt(lines []string, i int) string {
	if i < len(lines) {
		return lines[i]
	}
	return "<end of block>"
}

// cell escapes s for a Markdown table cell; GitHub and the site both turn
// \| back into | inside code spans.
func cell(s string) string { return strings.ReplaceAll(s, "|", `\|`) }

// textCell is cell for plain text (not a code span): it also escapes the
// characters HTML would read, so a placeholder such as <ipv4> shows as text
// on GitHub and is not taken for a tag by the site's Vue compiler.
func textCell(s string) string {
	return cell(strings.NewReplacer("&", "&amp;", "<", "&lt;", ">", "&gt;").Replace(s))
}

// renderRedactionCatalog renders the generated block: the table, one step
// per pattern and the full pipeline.
func renderRedactionCatalog(c redactCatalog) (string, error) {
	var b strings.Builder
	b.WriteString(patternsBegin + "\n\n")
	b.WriteString("| pattern | finds | example | false positives |\n|---|---|---|---|\n")
	for _, p := range c.Patterns {
		name := "`" + p.ID + "`"
		if p.VariantOf != "" {
			name += " (variant of `" + p.VariantOf + "`)"
		}
		ex := p.Cases[0]
		fmt.Fprintf(&b, "| %s | %s | `%s` becomes `%s` | %s |\n",
			name, textCell(p.Finds), cell(ex.In), cell(ex.Out), textCell(p.FalsePositives))
	}
	b.WriteString("\nThe step of each pattern, ready to paste into `steps`:\n\n")
	for _, p := range c.Patterns {
		js, err := json.Marshal(p.step())
		if err != nil {
			return "", err
		}
		fmt.Fprintf(&b, "`%s`:\n\n```json\n%s\n```\n\n", p.ID, js)
	}
	primary := c.primary()
	ids := make([]string, len(primary))
	for i, p := range primary {
		ids[i] = "`" + p.ID + "`"
	}
	fmt.Fprintf(&b, "Every pattern that is not a variant, in this order, as one pipeline for the `checkout` stream (%s):\n\n```json\n{\n  \"name\": \"checkout-redact\",\n  \"stage\": \"ingest\",\n  \"selector\": \"checkout\",\n  \"steps\": [\n", strings.Join(ids, ", "))
	for i, p := range primary {
		js, err := json.Marshal(p.step())
		if err != nil {
			return "", err
		}
		sep := ","
		if i == len(primary)-1 {
			sep = ""
		}
		fmt.Fprintf(&b, "    %s%s\n", js, sep)
	}
	b.WriteString("  ]\n}\n```\n\n")
	b.WriteString("What that pipeline does to two sample lines:\n\n```text\n")
	for _, cs := range c.Combined.Cases {
		fmt.Fprintf(&b, "before: %s\nafter:  %s\n", cs.In, cs.Out)
	}
	b.WriteString("```\n\n")
	fmt.Fprintf(&b, "Field names that usually hold sensitive values (the skill uses this to pick candidates; it is not a pipeline step): `%s`\n\n", cell(c.FieldNames.Pattern))
	b.WriteString(patternsEnd)
	return b.String(), nil
}

// The catalog must cover the pattern kinds the redaction page promises.
func TestRedactionCatalogCoverage(t *testing.T) {
	c := loadRedactCatalog(t, moduleRoot(t))
	var ids []string
	for _, p := range c.Patterns {
		ids = append(ids, p.ID)
	}
	for _, id := range []string{"email", "ipv4", "ipv6", "card", "card-keep-last4", "jwt", "bearer", "secret-kv", "secret-json", "phone-e164"} {
		if !slices.Contains(ids, id) {
			t.Errorf("patterns.json has no %q pattern", id)
		}
	}
}
