package index_test

// Benchmark fixture: deterministic synthetic corpora and verified-absent
// whole needles. The fixture is deliberately small (about 1 MiB of raw line
// bytes per corpus) so the full N x FPRate matrix stays a bounded run; the
// line shapes mirror what cmd/pushgen/gen generates for the Loki comparison;
// the template corpus also carries a deterministic multibyte UTF-8 suffix on
// every 128th record. The generator is copied into this fixture rather than
// importing cmd/pushgen/gen so the benchmark identity is pinned here by
// benchFixtureVersion and benchFixtureSeed.

import (
	"fmt"
	"runtime"
	"runtime/debug"
	"slices"
	"strconv"
	"strings"
	"time"

	"github.com/nathabonfim59/parkana/internal/index"
)

const (
	// benchFixtureVersion identifies the corpus and probe layout below.
	// Bump it whenever a change alters generated bytes or probe selection.
	benchFixtureVersion = 1
	// benchFixtureSeed fixes every pseudo-random choice in the fixture, so
	// the same record index always yields the same line and probe.
	benchFixtureSeed uint64 = 0x7061_726b_616e_6102

	// benchCorpusRawBytes is the per-corpus generation target in raw line
	// bytes. Generation stops after the line that reaches it, so a corpus
	// may overshoot by one line. Raw bytes are the sum of len(line) without
	// newline separators, the same definition as parkbench's
	// CorpusInfo.RawLineBytes.
	benchCorpusRawBytes int64 = 1 << 20

	// benchProbeMinLen and benchProbeMaxLen are the whole-needle lengths the
	// benchmark measures, one absent-probe class per length.
	benchProbeMinLen = 4
	benchProbeMaxLen = 8
	// benchProbesPerLength is the total number of verified-absent needles per
	// length class and corpus. Half are in-alphabet mutations and half use
	// any replacement byte; both classes are fixed across N and FPRate.
	benchProbesPerLength = 512

	// benchUnicodeEvery is the record cadence of the template corpus's
	// multibyte UTF-8 message suffix, and benchUnicodeSuffix is that suffix.
	// They make the realistic corpus exercise non-ASCII grams directly.
	benchUnicodeEvery  = 128
	benchUnicodeSuffix = " — 日本語のログ"
)

// benchCorpus is one generated corpus. Lines are deterministic for
// (benchFixtureVersion, benchFixtureSeed, corpus name).
type benchCorpus struct {
	name     string
	lines    []string
	rawBytes int64
}

// benchCorpora returns the two corpora the matrix runs over: a realistic
// pushgen-shaped template corpus and a high-cardinality corpus whose unique
// hex tokens stress the distinct-gram count.
func benchCorpora() ([]benchCorpus, error) {
	template, err := generateBenchCorpus("template", benchTemplateLine)
	if err != nil {
		return nil, err
	}
	highcard, err := generateBenchCorpus("highcard", benchHighCardLine)
	if err != nil {
		return nil, err
	}
	return []benchCorpus{template, highcard}, nil
}

// generateBenchCorpus renders lines until the raw-byte target is reached.
func generateBenchCorpus(name string, line func(int) string) (benchCorpus, error) {
	c := benchCorpus{name: name}
	for i := 0; c.rawBytes < benchCorpusRawBytes; i++ {
		l := line(i)
		if l == "" {
			return benchCorpus{}, fmt.Errorf("index benchmark: %s line %d is empty", name, i)
		}
		c.lines = append(c.lines, l)
		c.rawBytes += int64(len(l))
	}
	return c, nil
}

// benchTemplateLine mirrors cmd/pushgen/gen's corpus records: one of three
// line formats carrying the same fields pushgen emits, with a unique record
// id. It stands in for realistic application traffic.
func benchTemplateLine(i int) string {
	formats := [...]string{"json", "logfmt", "plain"}
	levels := [...]string{"info", "warn", "error"}
	pods := [...]string{"pod-a", "pod-b"}
	statuses := [...]int{200, 201, 204, 301, 400, 401, 403, 404, 500, 502, 503}
	sizes := [...]string{"128B", "512B", "1KiB", "4KiB", "64KiB", "256KiB", "1MiB", "4MiB"}
	msgs := [...]string{
		"request completed",
		"connection timed out",
		"cache miss",
		"user login succeeded",
		"disk quota exceeded",
		"retrying upstream",
		"invalid token",
		"slow query",
	}
	// Attribute order matches pushgen's NewCorpusRecord: latency, format,
	// level, pod, status, bytes, duration, size, msg.
	r := benchRNG(benchFixtureSeed + uint64(i))
	latency := float64(r.next()%5000)/10 + 0.5 // 0.5..500.4 ms, one decimal
	lat := strconv.FormatFloat(latency, 'f', -1, 64)
	format := formats[r.next()%uint64(len(formats))]
	level := levels[r.next()%uint64(len(levels))]
	pod := pods[r.next()%uint64(len(pods))]
	status := statuses[r.next()%uint64(len(statuses))]
	bytes := 64 + r.next()%65536
	duration := (time.Duration(1+r.next()%120_000) * time.Millisecond).String()
	size := sizes[r.next()%uint64(len(sizes))]
	msg := msgs[r.next()%uint64(len(msgs))]
	if i%benchUnicodeEvery == 0 {
		msg += benchUnicodeSuffix
	}

	switch format {
	case "json":
		return fmt.Sprintf(`{"id":%d,"stream":"api","level":%q,"pod":%q,"latency":%s,"bytes":%d,"duration":%q,"size":%q,"response":{"status":%d},"msg":%q}`,
			i, level, pod, lat, bytes, duration, size, status, msg)
	case "logfmt":
		return fmt.Sprintf("id=%d stream=api level=%s pod=%s status=%d latency=%s bytes=%d duration=%s size=%s msg=%q",
			i, level, pod, status, lat, bytes, duration, size, msg)
	default: // plain
		return fmt.Sprintf("%s %s status=%d latency=%sms bytes=%d duration=%s size=%s msg=%q id=%d",
			strings.ToUpper(level), pod, status, lat, bytes, duration, size, msg, i)
	}
}

// benchHighCardLine renders access, audit and nginx-shaped lines whose trace,
// token, span and path fields are unique per record, like pushgen's per-record
// trace and request ids but embedded in the line text.
func benchHighCardLine(i int) string {
	r := benchRNG(benchFixtureSeed ^ (uint64(i)+1)*0x9e37_79b9_7f4a_7c15)
	ts := time.Unix(1_700_000_000+int64(i), 0).UTC().Format("2006-01-02T15:04:05.000000Z")
	switch i % 3 {
	case 0:
		return fmt.Sprintf(`{"time":%q,"level":"info","service":"api","event":"audit","trace":%q,"token":%q,"id":%d}`,
			ts, benchHexToken(&r, 32), benchHexToken(&r, 64), i)
	case 1:
		return fmt.Sprintf(`ts=%s level=warn service=checkout msg="retrying upstream" id=%d latency_ms=%d trace_id=%s span_id=%s path=/api/v1/orders/%d`,
			ts, i, 1+r.next()%5000, benchHexToken(&r, 32), benchHexToken(&r, 16), i)
	default:
		return fmt.Sprintf(`10.0.%d.%d - - [%s] "GET /api/v1/search/%d HTTP/1.1" %d %d`,
			r.next()%256, r.next()%256, ts, i, 200+r.next()%4, 1+r.next()%65536)
	}
}

// benchRNG is a splitmix64 stream, the generator pushgen and parkbench use.
type benchRNG uint64

func (r *benchRNG) next() uint64 {
	*r += 0x9e37_79b9_7f4a_7c15
	z := uint64(*r)
	z = (z ^ (z >> 30)) * 0xbf58_476d_1ce4_e5b9
	z = (z ^ (z >> 27)) * 0x94d0_49bb_1331_11eb
	return z ^ (z >> 31)
}

// benchHexToken appends n lowercase hex digits drawn from r.
func benchHexToken(r *benchRNG, n int) string {
	const digits = "0123456789abcdef"
	var b strings.Builder
	b.Grow(n)
	for range n {
		b.WriteByte(digits[r.next()&0xf])
	}
	return b.String()
}

// probeSet is one length class of fixed absent needles. inAlphabet probes
// mutate the final byte to another byte observed in the corpus; anyByte probes
// mutate it to a replacement from a fixed set that does not consult the corpus
// alphabet (the replacement may still happen to occur there). Both classes are
// verified absent with an exact substring search. all is the union used for
// the headline false-positive rate, so the probe set is identical for every N
// and FPRate cell.
type probeSet struct {
	inAlphabet []string
	anyByte    []string
	all        []string
}

// needleSets holds absent probes indexed by byte length.
type needleSets [benchProbeMaxLen + 1]probeSet

// corpusAlphabet returns the distinct byte values observed in the corpus,
// sorted. In-alphabet probes only use these bytes.
func corpusAlphabet(c benchCorpus) []byte {
	var seen [256]bool
	for _, line := range c.lines {
		for _, b := range []byte(line) {
			seen[b] = true
		}
	}
	out := make([]byte, 0, 256)
	for b := range 256 {
		if seen[b] {
			out = append(out, byte(b))
		}
	}
	return out
}

// benchAbsentProbes builds a fixed, deterministic set of whole needles of
// lengths 4..8 and verifies each one is absent from the corpus with an exact
// substring search before it may be used in a false-positive calculation.
// Every probe is a real corpus substring with its final byte replaced. The
// in-alphabet half replaces that byte with another byte observed in the
// corpus, so it looks like plausible data and exercises structural and
// common-gram false positives; the anyByte half uses a replacement from a
// fixed set and does not guarantee the byte is outside the corpus alphabet.
// Both share grams with present data for every gram length shorter than the
// needle. A length-L needle cannot share its L-grams with the
// corpus and still be absent; that case measures the bloom's per-gram
// collision rate alone.
func benchAbsentProbes(c benchCorpus, perLen int) (needleSets, error) {
	if len(c.lines) == 0 {
		return needleSets{}, fmt.Errorf("index benchmark: %s corpus has no lines", c.name)
	}
	if perLen < 2 {
		return needleSets{}, fmt.Errorf("index benchmark: per-length probe count %d must be at least 2", perLen)
	}
	alphabet := corpusAlphabet(c)
	if len(alphabet) < 2 {
		return needleSets{}, fmt.Errorf("index benchmark: %s corpus has %d distinct bytes, need at least 2", c.name, len(alphabet))
	}
	const maxAttempts = 1 << 22
	anyReplacements := []byte("Qz7~#_")
	var out needleSets
	r := benchRNG(benchFixtureSeed ^ 0x7072_6f62_6573) // "probes"
	for length := benchProbeMinLen; length <= benchProbeMaxLen; length++ {
		// Half in-alphabet, half any-byte: a fixed split per corpus and
		// length, reused unchanged by every N and FPRate cell.
		quotaIn := perLen / 2
		quotaAny := perLen - quotaIn
		seen := make(map[string]struct{}, perLen)
		var inAlphabet, anyByte []string
		for attempt := 0; attempt < maxAttempts && (len(inAlphabet) < quotaIn || len(anyByte) < quotaAny); attempt++ {
			line := c.lines[r.next()%uint64(len(c.lines))]
			if len(line) < length {
				continue
			}
			pos := int(r.next() % uint64(len(line)-length+1))
			cand := []byte(line[pos : pos+length])
			mut := len(cand) - 1
			orig := cand[mut]
			if len(inAlphabet) < quotaIn {
				// Walk the corpus alphabet from a deterministic offset so
				// the probe's final gram stays in-alphabet.
				start := int(r.next() % uint64(len(alphabet)))
				for k := range len(alphabet) {
					repl := alphabet[(start+k)%len(alphabet)]
					if repl == orig {
						continue
					}
					cand[mut] = repl
					needle := string(cand)
					cand[mut] = orig
					if _, dup := seen[needle]; dup {
						continue
					}
					if lineContains(c.lines, needle) {
						continue
					}
					seen[needle] = struct{}{}
					inAlphabet = append(inAlphabet, needle)
					break
				}
				continue
			}
			for _, repl := range anyReplacements {
				if repl == orig {
					continue
				}
				cand[mut] = repl
				needle := string(cand)
				cand[mut] = orig
				if _, dup := seen[needle]; dup {
					continue
				}
				if lineContains(c.lines, needle) {
					continue
				}
				seen[needle] = struct{}{}
				anyByte = append(anyByte, needle)
				break
			}
		}
		if len(inAlphabet) != quotaIn || len(anyByte) != quotaAny {
			return needleSets{}, fmt.Errorf(
				"index benchmark: %s corpus: found %d/%d in-alphabet and %d/%d any-byte absent %d-byte probes",
				c.name, len(inAlphabet), quotaIn, len(anyByte), quotaAny, length)
		}
		out[length] = probeSet{
			inAlphabet: inAlphabet,
			anyByte:    anyByte,
			all:        append(slices.Clone(inAlphabet), anyByte...),
		}
	}
	return out, nil
}

// lineContains reports whether any line contains needle as a byte substring,
// the exact predicate index.Filter.MayContain must not contradict.
func lineContains(lines []string, needle string) bool {
	return slices.ContainsFunc(lines, func(line string) bool {
		return strings.Contains(line, needle)
	})
}

// buildMem is one builder's allocation profile, measured once per benchmark
// configuration in a builder instance separate from the timed loop.
type buildMem struct {
	// totalAlloc is the cumulative TotalAlloc delta of NewBuilder and Add,
	// including garbage. It bounds peak live memory from above.
	totalAlloc uint64
	// retained is settled live heap after a full GC and sweep with the
	// builder still referenced. HeapAlloc is process-global, so this is an
	// approximate measurement, not an exact per-builder accounting; the
	// benchmark labels it as such.
	retained uint64
	grams    int
}

// measureBuild builds one sidecar's gram set and reports its allocation
// profile. Corpus generation happens outside this helper, and the corpus lines
// stay live across both snapshots in every case; only the builder's
// contribution is reported.
func measureBuild(p index.Params, lines []string) (buildMem, error) {
	// FreeOSMemory completes a GC cycle and the sweep, so the retained
	// snapshot is settled rather than inflated by unswept garbage.
	debug.FreeOSMemory()
	var before runtime.MemStats
	runtime.ReadMemStats(&before)

	b, err := index.NewBuilder(p)
	if err != nil {
		return buildMem{}, err
	}
	for _, line := range lines {
		b.Add(line)
	}

	debug.FreeOSMemory()
	var after runtime.MemStats
	runtime.ReadMemStats(&after)
	// Keep both the corpus and the builder live through the settled
	// snapshot: otherwise the GC can reclaim the caller's lines and
	// understate retained memory.
	runtime.KeepAlive(lines)
	runtime.KeepAlive(b)

	retained := uint64(0)
	if after.HeapAlloc > before.HeapAlloc {
		retained = after.HeapAlloc - before.HeapAlloc
	}
	total := after.TotalAlloc - before.TotalAlloc

	// Encode once so an over-cap configuration is reported here rather than
	// surfacing as an unexplained zero byte count in the benchmark table.
	if _, err := b.Encode(); err != nil {
		return buildMem{}, fmt.Errorf("index benchmark: N=%d FPRate=%g: %w", p.N, p.FPRate, err)
	}
	return buildMem{totalAlloc: total, retained: retained, grams: b.Grams()}, nil
}
